import { defineConfig } from "vite";
import { createMultiLocalePlugin } from "vite-ssr-i18n-basic";

// Pages come from scripts/build-pages.mjs; run it before vite (npm run build).
// The plugin version comes from guilbep/vite-ssr-i18n-basic#4 (unreleased):
// it adds minifyHtml and drops the root redirect for a single locale.
export default defineConfig({
  plugins: [
    createMultiLocalePlugin({
      locales: ["en"],
      defaultLocale: "en",
      siteUrl: "https://co2-calculator.epfl.ch",
      emitSitemaps: false,
      emit404s: false,
      emitWebmanifest: false,
      linkRewrite: "off",
      // nginx gzips; minifying was 1.5 s of a 1.8 s build.
      minifyHtml: false,
    }),
    {
      name: "virtual-entry",
      resolveId(id) {
        if (id === "virtual:static-site") return id;
      },
      load(id) {
        if (id === "virtual:static-site") {
          return "// Static site generated by multi-locale plugin";
        }
      },
    },
  ],
  publicDir: false,
  build: {
    outDir: "dist",
    emptyOutDir: false,
    rollupOptions: {
      input: "virtual:static-site",
      output: { entryFileNames: ".vite/[name].js" },
    },
  },
});
