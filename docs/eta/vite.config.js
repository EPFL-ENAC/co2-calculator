import { defineConfig } from "vite";
import { createMultiLocalePlugin } from "vite-ssr-i18n-basic";
import { mermaid, pythonMarkdownIds } from "./scripts/marked-extensions.mjs";

// The plugin renders ../src/**/*.md itself; scripts/prepare.mjs writes the
// indexes, nav data and routes.config.json first (npm run build). The
// plugin version is guilbep/vite-ssr-i18n-basic#5 (unreleased).
export default defineConfig({
  plugins: [
    createMultiLocalePlugin({
      pagesDir: "../src",
      markdown: { extensions: [pythonMarkdownIds, mermaid] },
      locales: ["en"],
      defaultLocale: "en",
      siteUrl: "https://co2-calculator.epfl.ch",
      emitSitemaps: false,
      emit404s: false,
      emitWebmanifest: false,
      linkRewrite: "off",
      // nginx gzips; minifying was 1.5 s of a 1.8 s build.
      minifyHtml: false,
    }),
    {
      name: "virtual-entry",
      resolveId(id) {
        if (id === "virtual:static-site") return id;
      },
      load(id) {
        if (id === "virtual:static-site") {
          return "// Static site generated by multi-locale plugin";
        }
      },
    },
  ],
  publicDir: false,
  build: {
    outDir: "dist",
    emptyOutDir: false,
    rollupOptions: {
      input: "virtual:static-site",
      output: { entryFileNames: ".vite/[name].js" },
    },
  },
});
